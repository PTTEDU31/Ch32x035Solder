#!/usr/bin/env python3
"""Generate src/fonts.c.

- font8x16: ASCII 8x16 bitmap (Terminus PSF2), 1 bpp.
- font_big: '0'-'9', '-', 2 bpp anti-aliased digits (DejaVu Sans Condensed
  Bold), fixed cell FONT_BIG_W x FONT_BIG_H, four pixels per byte, first
  pixel in the high bits.
- font_mid: printable ASCII + degree sign at code 127, 2 bpp, proportional,
  with a width table (DejaVu Sans Condensed Bold). Rows are padded to whole
  bytes (stride (w + 3) / 4); identical glyphs (the unused ones) share data.

Usage: python3 tools/gen_fonts.py > src/fonts.c
"""
import gzip
import struct

from PIL import Image, ImageDraw, ImageFont

PSF = "/usr/share/kbd/consolefonts/Lat2-Terminus16.psfu.gz"
TTF = "/usr/share/fonts/TTF/DejaVuSansCondensed-Bold.ttf"

BIG_W, BIG_H, BIG_PT = 48, 60, 76
BIG_CHARS = "0123456789-"
MID_H, MID_PT = 22, 20
MID_FIRST, MID_LAST = 32, 127  # 127 renders as the degree sign
# Only these characters get real glyphs; the rest are empty 2 px cells.
MID_SET = set("0123456789.+-% CFAEGHIKLNOPRSTWVYZDBMabcdeghiklmnoprstuvwfy") | {"\x7f"}


def small_font():
    d = gzip.open(PSF).read()
    magic, ver, hs, flags, n, cs, h, w = struct.unpack("<8I", d[:32])
    assert magic == 0x864AB572 and w == 8 and h == 16
    glyphs = d[hs:hs + n * cs]
    return [glyphs[c * cs:(c + 1) * cs] for c in range(32, 127)]


def pack4(img):
    out = bytearray()
    w, h = img.size
    for y in range(h):
        for x in range(0, w, 2):
            a = img.getpixel((x, y)) >> 4
            b = img.getpixel((x + 1, y)) >> 4 if x + 1 < w else 0
            out.append((a << 4) | b)
    return bytes(out)


def pack2(img):
    out = bytearray()
    w, h = img.size
    for y in range(h):
        for x in range(0, w, 4):
            v = 0
            for k in range(4):
                p = (img.getpixel((x + k, y)) + 42) // 85 if x + k < w else 0  # 0..255 -> 0..3
                v = (v << 2) | p
            out.append(v)
    return bytes(out)

def big_font():
    f = ImageFont.truetype(TTF, BIG_PT)
    top = f.getbbox("0")[1]
    out = []
    for ch in BIG_CHARS:
        img = Image.new("L", (BIG_W, BIG_H), 0)
        x0, _, x1, _ = f.getbbox(ch)
        ImageDraw.Draw(img).text(((BIG_W - (x1 - x0)) // 2 - x0, -top), ch, font=f, fill=255)
        out.append(pack2(img))
    return out


def mid_font():
    f = ImageFont.truetype(TTF, MID_PT)
    ascent = f.getmetrics()[0]
    widths, glyphs = [], []
    for c in range(MID_FIRST, MID_LAST + 1):
        ch = "°" if c == 127 else chr(c)
        if chr(c) not in MID_SET:
            widths.append(2)
            glyphs.append(bytes(MID_H))  # (2 + 3) // 4 = 1 byte per row
            continue
        w = int(round(f.getlength(ch)))
        w += w & 1  # even width: whole bytes per row
        w = max(w, 2)
        img = Image.new("L", (w, MID_H), 0)
        ImageDraw.Draw(img).text((0, MID_H - 3 - ascent), ch, font=f, fill=255)
        widths.append(w)
        glyphs.append(pack2(img))
    return widths, glyphs


def emit(name, glyphs, comment):
    print(f"/* {comment} */")
    print(f"const uint8_t {name}[] = {{")
    for g in glyphs:
        for i in range(0, len(g), 16):
            print("    " + ", ".join(f"0x{b:02X}" for b in g[i:i + 16]) + ",")
    print("};\n")


print("/* Generated by tools/gen_fonts.py - do not edit. */")
print('#include "fonts.h"\n')
emit("font8x16", small_font(), "ASCII 32..126, 8x16, 1 bpp, Terminus (OFL)")
emit("font_big", big_font(), f"'{BIG_CHARS}', {BIG_W}x{BIG_H}, 2 bpp, DejaVu Sans Condensed Bold")
widths, glyphs = mid_font()
offs, o, seen, uniq = [], 0, {}, []
for g in glyphs:
    if g not in seen:
        seen[g] = o
        uniq.append(g)
        o += len(g)
    offs.append(seen[g])
glyphs = uniq
print("/* font_mid: ASCII 32..126 + 127 = degree sign, height %d, 2 bpp */" % MID_H)
print("const uint8_t font_mid_w[] = {" + ", ".join(map(str, widths)) + "};")
print("const uint16_t font_mid_off[] = {" + ", ".join(map(str, offs)) + "};")
emit("font_mid", glyphs, "glyph data, rows of (w + 3) / 4 bytes")
